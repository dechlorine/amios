from random import random
from math import log, floor, ceil
from statistics import mean, stdev
import matplotlib.pyplot as plt
from pandas import DataFrame

def random_uniform(N):
    x = random()
    return x * N

def random_exp(N):
    x = random()
    return log(1 - x) * (-1/N)

def random_triangle(N):
    x = random()
    return N - N * (1 - x)**0.5

def construct_function(function_name, N):
    def generator():
          return function_name(N)
    return generator

def generate(N, func):
    nums = []
    for x in range(N):
        num = func()
        nums.append(num)
    return nums

exp_service_function = construct_function(random_exp, 1)
uniform_service_function = construct_function(random_uniform, 2)
triangle_service_function = construct_function(random_triangle, 3)

def model_of_mass_service(intensity, order_amount, service_function, max_queue_length):
    arrival_function = construct_function(random_exp, intensity)

    # arrival_time_distance - время с прибытия предыдущего покупателя
    # arrival_time - время с прибытия первого покупателя
    # service_time - время обслуживания
    # service_delay - длина очереди в минутах на момент прибытия покупателя
    # queue_pop_time - время окончания ожидания в очереди
    # queue_length - количество заявок в очереди
    # is_failed_order - не обслуженные заявки
    df = DataFrame(columns=['arrival_time_distance',
                            'arrival_time',
                            'service_time',
                            'service_delay',
                            'queue_pop_time',
                            'queue_length',
                            'is_failed_order'])

    for ind in range(order_amount):
        service_time = service_function()
        is_failed_order = 0
        if ind != 0:
            arrival_time_distance = arrival_function()
            arrival_time = arrival_time_distance + df.loc[ind - 1, 'arrival_time']
            queue_time = df.loc[ind - 1, 'service_time'] + df.loc[ind - 1, 'service_delay']
            delay_time = max(queue_time - arrival_time_distance, 0)
            queue_pop_time = arrival_time + delay_time
            queue_length  = df.loc[ind - 1, 'queue_length']
            prev_ind = ind - 1
            counter = queue_length

            while counter > 0:
                if df.loc[prev_ind, 'is_failed_order'] == 0 and df.loc[prev_ind, 'queue_pop_time'] < arrival_time:
                    queue_length -= 1
                if df.loc[prev_ind, 'is_failed_order'] == 0:
                    counter -= 1
                prev_ind -= 1

            if delay_time > 0:
                queue_length += 1


        else:
            arrival_time_distance = 0
            arrival_time = 0
            delay_time = 0
            queue_pop_time = 0
            queue_length = 0


        if queue_length > max_queue_length:
            is_failed_order = 1
            queue_length -= 1
            service_time = 0



        df.loc[ind] = [arrival_time_distance,
                       arrival_time,
                       service_time,
                       delay_time,
                       queue_pop_time,
                       queue_length,
                       is_failed_order]

    # print(df)

    failed_orders_amount = sum(df['is_failed_order'])
    failed_ratio = failed_orders_amount / order_amount
    QM = max(df['queue_length'])
    QA = sum(df.loc[df['is_failed_order'] == 0, 'service_delay']) / (df.loc[order_amount-1, "arrival_time"] + df.loc[order_amount-1, "service_delay"] + df.loc[order_amount-1, "service_time"])
    QZ = (df["queue_length"] == 0).sum()
    QT = sum(df.loc[df['is_failed_order'] == 0, 'service_delay']) / (order_amount)
    QX = sum(df.loc[df['is_failed_order'] == 0, 'service_delay']) / (order_amount - QZ)
    FR = sum(df['service_time']) / (df.loc[order_amount-1, "arrival_time"] + df.loc[order_amount-1, "service_delay"] + df.loc[order_amount-1, "service_time"])
    FT = sum(df['service_time']) / (order_amount - failed_orders_amount)
    print('QM:', QM)
    print('QA:', QA)
    print('QZ:', QZ)
    print('QT:', QT)
    print('QX:', QX)
    print('FR:', FR)
    print('FT:', FT)
    print('FAILED:', failed_orders_amount)
    print('FAILED RATIO:', failed_ratio)

